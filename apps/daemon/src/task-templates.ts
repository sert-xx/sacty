/** リポジトリの URL から、題に出す短い名前（owner/name）を作る。形が違えば、そのまま。 */
function shortName(repo: string): string {
  const match = /^https?:\/\/[^/]+\/([^/]+\/[^/]+?)(?:\.git)?\/?$/.exec(repo);
  return match?.[1] ?? repo;
}

