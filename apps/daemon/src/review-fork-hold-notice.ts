/*
 * フォークからの PR の、新しいコミットを自動ではレビューしないことを、その PR に知らせるコメント（PBI-461）。
 * PR を見ている人は Sacty の画面を開かないので、Sacty の内部の言葉（タスク・見守り・再レビューの仕組み）を使わずに書く。
 * 先頭の目印は、Sacty が頼みで投稿したコメントのもの（人の指摘・作者の返信として数えない）。
 */

/** 新しいコミットを自動ではレビューしないことを知らせる本文。 */
export function buildForkHoldNotice(commit: string): string {
  return [
    "<!-- sacty-comment:fork-hold -->",
    `この PR はフォークからのため、新しいコミット（\`${commit.slice(0, 7)}\`）は自動ではレビューされません。レビューが必要なときは、GitHub でレビューを再依頼してください。`,
  ].join("\n");
}
